// Two documents share this script: the privacy policy (privacy.html) and the consent text (consent.html),
// which since 2025 must be a separate document. Operator details come from config.js (privacy block).
const el = (tag, text, attrs = {}) => Object.assign(document.createElement(tag), { textContent: text, ...attrs });
const page = document.body.dataset.page;

try {
  const cfg = await fetch('/api/config').then((r) => r.json());
  const p = cfg.privacy || {};
  const shop = cfg.shop.name;
  const months = p.retentionMonths || 12;
  const op = `${p.operator}, ИНН ${p.inn}`;
  const tg = p.telegram;

  const policy = [
    ['Кто обрабатывает данные', `${op} (далее — оператор). Сайт: ${shop}. Связь по вопросам данных: ${p.email}.`],
    ['Какие данные и зачем', 'Имя, номер телефона и комментарий из формы записи, а также выбранные услуга, мастер, дата и время. Они нужны, чтобы принять запись, связаться с вами при необходимости и провести визит.'],
    ['Основание', 'Ваше согласие. Оно оформлено отдельным документом, на который ведёт галочка в форме записи. Без согласия запись не отправляется.'],
    ['Как долго хранится', `Записи хранятся ${months} мес. после даты визита и затем удаляются из базы сайта автоматически.`],
    ['Кому передаются', tg
      ? 'Данные записи (имя, телефон, услуга, время, комментарий) отправляются администратору в мессенджер Telegram. Копия остаётся в переписке администратора, и сайт не может её удалить автоматически: при отзыве согласия администратор удаляет сообщения вручную. Других получателей нет, данные не продаются и не передаются для рекламы.'
      : 'Данные видит только администратор. Они не продаются и не передаются третьим лицам для рекламы.'],
    ['Сторонние сервисы', 'Шрифты хранятся на самом сайте. Карта Яндекса загружается только после нажатия кнопки «Показать карту»: тогда этот сервис получает технические данные вашего браузера (например, IP-адрес) и устанавливает собственные cookie. Пока вы не нажали, страница не обращается к сторонним сервисам. Сам сайт не устанавливает cookie и не использует счётчики аналитики.'],
    ['Ваши права', `Вы можете отозвать согласие, узнать, какие данные о вас хранятся, исправить или удалить их. Напишите на ${p.email}, ответ придёт в течение 10 рабочих дней.`],
  ];

  const consent = [
    ['Оператор', op, `Почта для обращений: ${p.email}.`],
    ['Данные', 'Я даю согласие на обработку моих персональных данных: имени, номера телефона и текста комментария, указанных в форме записи на сайте, а также сведений о выбранной услуге, мастере, дате и времени визита.'],
    ['Цель', 'Принять и выполнить запись, связаться со мной по вопросам визита.'],
    ['Действия', 'Сбор, запись, хранение, использование, уничтожение' + (tg ? ' и передача администратору через мессенджер Telegram.' : '.')],
    ['Срок', `Согласие действует до отзыва, а данные хранятся ${months} мес. после даты визита.`],
    ['Отзыв', `Я могу отозвать согласие в любой момент, написав оператору на ${p.email}. Подробнее: `],
  ];

  const root = document.getElementById('legal');
  const back = Object.assign(el('a', '← На сайт'), { href: './' });
  if (page === 'consent') {
    document.title = `Согласие на обработку персональных данных — ${shop}`;
    root.replaceChildren(el('h1', 'Согласие на обработку персональных данных'),
      ...consent.flatMap(([h, t, extra]) => [el('h2', h), el('p', [t, extra].filter(Boolean).join(' ')), ...(h === 'Отзыв' ? [Object.assign(el('a', 'политика конфиденциальности'), { href: 'privacy.html' })] : [])]),
      el('p', ''), back);
  } else {
    document.title = `Политика конфиденциальности — ${shop}`;
    root.replaceChildren(el('h1', 'Политика конфиденциальности'),
      ...policy.flatMap(([h, t]) => [el('h2', h), el('p', t)]),
      Object.assign(el('a', 'Текст согласия на обработку данных'), { href: 'consent.html' }), el('p', ''), back);
  }
} catch {
  document.getElementById('legal').textContent = 'Не удалось загрузить страницу. Обновите её.';
}
